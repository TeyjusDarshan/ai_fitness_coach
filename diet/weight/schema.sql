-- Weight tracking (diet/weight/). Applied to Supabase as the migration
-- `weight_tracking`; kept here so the schema can be reviewed with the code.
-- Like the other per-user tables, RLS stays off (see CLAUDE.md's warning).

-- Her weight on a day (her local date). WhatsApp text / voice (via the
-- router) or the coach; the latest reading of a day replaces the earlier
-- one. Readings far from her 7-day average are never written.
create table public.weight_logs (
  id int4 generated by default as identity primary key,
  user_id text not null references public.user_profiles(user_id) on delete cascade,
  measured_on date not null,
  weight_kg numeric(5,1) not null check (weight_kg between 30 and 200),
  source varchar not null check (source in ('whatsapp_text', 'whatsapp_voice', 'coach', 'setup')),
  inbound_message_id int4 references public.inbound_messages(id) on delete set null,
  raw text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, measured_on)
);
create index weight_logs_inbound_message_id_idx on public.weight_logs(inbound_message_id);

-- One row per client per closed week (Mon–Sun in her time zone), written
-- by the Sunday job: the numbers, the decision from the flowchart, and the
-- WhatsApp summary.
create table public.weight_weeks (
  id int4 generated by default as identity primary key,
  user_id text not null references public.user_profiles(user_id) on delete cascade,
  week_start date not null,
  goal varchar not null check (goal in ('lose', 'gain', 'maintain')),
  readings int2 not null,
  avg_kg numeric(5,2),
  previous_avg_kg numeric(5,2),
  change_kg numeric(5,2),
  expected_kg numeric(4,2),
  classification varchar,
  period_week bool not null default false,
  log_coverage numeric(4,3),
  avg_logged_kcal int4,
  target_kcal int4,
  outcome varchar not null,
  kcal_delta int4,
  proposed_kcal int4,
  streak int2 not null default 0,
  streak_stalled bool not null default false,
  streak_direction varchar check (streak_direction in ('up', 'down')),
  reason text,
  mode varchar not null check (mode in ('shadow', 'live')),
  message_text text,
  status varchar not null check (status in ('pending', 'sent', 'shadow', 'skipped_window_closed', 'skipped_late', 'failed')),
  error text,
  sent_at timestamptz,
  created_at timestamptz not null default now(),
  unique (user_id, week_start)
);

-- Every change to her calorie targets: suggested by the weekly rules (the
-- coach accepts or rejects), the coach's own edit, or a goal switch when
-- she reaches her target. Accepted rows start the cool-down and are the
-- markers on her chart.
create table public.nutrition_target_changes (
  id int4 generated by default as identity primary key,
  user_id text not null references public.user_profiles(user_id) on delete cascade,
  week_id int4 references public.weight_weeks(id) on delete set null,
  source varchar not null check (source in ('weekly_rule', 'coach_manual', 'goal_switch')),
  from_targets jsonb,
  to_targets jsonb not null,
  new_goal varchar check (new_goal in ('lose', 'gain', 'maintain')),
  new_goal_kg numeric(5,1),
  reason text,
  status varchar not null check (status in ('pending', 'accepted', 'rejected', 'superseded')),
  decided_at timestamptz,
  notified_at timestamptz,
  created_at timestamptz not null default now()
);
create index nutrition_target_changes_user_id_idx on public.nutrition_target_changes(user_id, created_at);
create index nutrition_target_changes_week_id_idx on public.nutrition_target_changes(week_id);

-- Weigh-in messages we start: the one-time how-to (`intro`) and the 10:00
-- nudge (`morning`). Sent only while her 24-hour window is open.
create table public.weight_nudges (
  id int4 generated by default as identity primary key,
  user_id text not null references public.user_profiles(user_id) on delete cascade,
  nudge_date date not null,
  kind varchar not null check (kind in ('intro', 'morning')),
  status varchar not null check (status in ('pending', 'sent', 'skipped_logged', 'skipped_window_closed', 'failed')),
  error text,
  sent_at timestamptz,
  created_at timestamptz not null default now(),
  unique (user_id, nudge_date, kind)
);

-- Her current weight goal once it differs from her diet setup (reaching a
-- lose / gain target switches her to maintain). Null = diet_setup's goal.
alter table public.user_profiles
  add column weight_goal varchar check (weight_goal in ('lose', 'gain', 'maintain')),
  add column weight_goal_kg numeric(5,1);

-- The router's new label, and the reading a message produced.
alter table public.inbound_messages drop constraint inbound_messages_route_check;
alter table public.inbound_messages add constraint inbound_messages_route_check
  check (route in ('diet_checkin', 'question_reply', 'weight_checkin', 'other'));
alter table public.inbound_messages
  add column weight_log_id int4 references public.weight_logs(id) on delete set null;
create index inbound_messages_weight_log_id_idx on public.inbound_messages(weight_log_id);

-- Her setup weight is her first reading.
insert into public.weight_logs (user_id, measured_on, weight_kg, source)
select user_id,
       ((diet_setup->>'completed_at')::timestamptz at time zone coalesce(timezone, 'Asia/Kolkata'))::date,
       round((diet_setup->>'weight_kg')::numeric, 1),
       'setup'
from public.user_profiles
where diet_setup is not null and diet_setup->>'weight_kg' is not null
on conflict (user_id, measured_on) do nothing;
